-- 1) Who is the admin? Only this email can add / edit / delete anything.
--    CHANGE THIS to the email you will log in with (keep the quotes).
create or replace function public.is_admin() returns boolean
language sql stable as $$
  select coalesce(auth.jwt() ->> 'email', '') = lower('CHANGE_ME@example.com')
$$;

-- 2) Tables
create table if not exists public.categories (
  slug        text primary key,                 -- short id used in links, e.g. 'suvs'
  name        text not null,                    -- shown in filters, e.g. 'SUVs'
  label       text,                             -- small badge on a car card, e.g. 'SUV'
  sort_order  int  not null default 100
);

create table if not exists public.cars (
  id          bigint generated by default as identity primary key,
  name        text    not null,
  year        int     not null,
  seats       int     not null,
  fuel        text    not null default 'Petrol',
  price       numeric,                          -- Naira per day, empty = "Price on request"
  categories  text[]  not null default '{}',    -- list of category slugs
  image_path  text,                             -- photo files in the car-images bucket
  thumb_path  text,
  legacy_img  text,                             -- old photo bundled with the website (first 12 cars)
  visible     boolean not null default true,    -- false = hidden from the public site
  sort_order  int     not null default 100,
  created_at  timestamptz not null default now()
);

-- 3) Security: everyone can READ visible cars, only the admin can change data
alter table public.categories enable row level security;
alter table public.cars       enable row level security;

drop policy if exists "public read categories" on public.categories;
create policy "public read categories" on public.categories for select to anon, authenticated using (true);
drop policy if exists "admin manage categories" on public.categories;
create policy "admin manage categories" on public.categories for all to authenticated using (public.is_admin()) with check (public.is_admin());

drop policy if exists "public read visible cars" on public.cars;
create policy "public read visible cars" on public.cars for select to anon, authenticated using (visible = true or public.is_admin());
drop policy if exists "admin manage cars" on public.cars;
create policy "admin manage cars" on public.cars for all to authenticated using (public.is_admin()) with check (public.is_admin());

grant select on public.categories, public.cars to anon;
grant select, insert, update, delete on public.categories, public.cars to authenticated;

-- 4) Photo storage (public bucket, only the admin can upload or delete)
insert into storage.buckets (id, name, public) values ('car-images', 'car-images', true)
on conflict (id) do update set public = true;

drop policy if exists "admin upload car images" on storage.objects;
create policy "admin upload car images" on storage.objects for insert to authenticated with check (bucket_id = 'car-images' and public.is_admin());
drop policy if exists "admin update car images" on storage.objects;
create policy "admin update car images" on storage.objects for update to authenticated using (bucket_id = 'car-images' and public.is_admin());
drop policy if exists "admin delete car images" on storage.objects;
create policy "admin delete car images" on storage.objects for delete to authenticated using (bucket_id = 'car-images' and public.is_admin());

